function tiltBok(b, g){
  const B=(b||0)*Math.PI/180, G=(g||0)*Math.PI/180;
  const ux=-Math.cos(B)*Math.sin(G), uy=Math.sin(B), uz=Math.cos(B)*Math.cos(G);
  return Math.atan2(-ux, Math.hypot(uy, uz)) * 180/Math.PI;
}
