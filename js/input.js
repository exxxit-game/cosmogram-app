  const bs=new Array(h.length);
  for(let i=0;i<h.length;i++){ const g=h[i].g, b=h[i].b;
    if(g<mng)mng=g; if(g>mxg)mxg=g; if(b<mnb)mnb=b; if(b>mxb)mxb=b; bs[i]=b; }
  bs.sort((x,y)=>x-y);
