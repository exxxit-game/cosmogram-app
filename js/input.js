/* ---------- Клавиатура (desktop fallback: стрелки + WASD + рус. раскладка) ---------- */
/* ---------- Геймпад (v1.99.4 «Штурвал»): стик и крестовина рулят, А — взлёт, Start — пауза ---------- */
/* Рулит в том же канале, что и стрелки: физика не знает, кто за штурвалом.
   Свои флаги помечает — чужие (клавиатура) не трогает. Браузер отдаёт геймпад
   только после первого нажатия на нём — правило приватности, нам оно на руку:
   «нажми А, чтобы взлететь» — и дверь уже открыта. */
const PAD_DZ=.2; // мёртвая зона стика: дрейф без нажатия не рулит
let padPrev={a:false,st:false}, padLastId=null; // padLastId — v1.99.7: стыковка/отстыковка на ленту
const padOwn={l:false,r:false,u:false,d:false}; // какие флаги руля поставил штурвал — только их и снимает
function pollGamepad(){
  if(typeof navigator==='undefined'||typeof navigator.getGamepads!=='function') return;
  let gp=null;
  try{ const pads=navigator.getGamepads();
    for(let i=0;i<pads.length;i++){ if(pads[i]&&pads[i].connected){ gp=pads[i]; break; } }
  }catch(e){ return; }
  const pid=gp?String(gp.id||'pad'):null; // v1.99.7 «Чёрный ящик»: фронты стыковки — не каждый кадр
  if(pid!==padLastId){ if(typeof BB!=='undefined') BB.log('helm', pid!=null?'connected '+pid.slice(0,40):'disconnected'); padLastId=pid; }
  if(!gp){ padPrev.a=padPrev.st=false;
    if(padOwn.l){input.keyL=false;padOwn.l=false;} if(padOwn.r){input.keyR=false;padOwn.r=false;}
    if(padOwn.u){input.keyU=false;padOwn.u=false;} if(padOwn.d){input.keyD=false;padOwn.d=false;}
    return; } // штурвал отстыковался — сдаём только свои флаги
  const ax=gp.axes[0]||0, ay=gp.axes[1]||0;
  const btn=i=>!!(gp.buttons[i]&&gp.buttons[i].pressed);
  const L=ax<-PAD_DZ||btn(14), R=ax>PAD_DZ||btn(15), U=ay<-PAD_DZ||btn(12), D=ay>PAD_DZ||btn(13);
  if(L){input.keyL=true;padOwn.l=true;} else if(padOwn.l){input.keyL=false;padOwn.l=false;}
  if(R){input.keyR=true;padOwn.r=true;} else if(padOwn.r){input.keyR=false;padOwn.r=false;}
  if(U){input.keyU=true;padOwn.u=true;} else if(padOwn.u){input.keyU=false;padOwn.u=false;}
  if(D){input.keyD=true;padOwn.d=true;} else if(padOwn.d){input.keyD=false;padOwn.d=false;}
  const a=btn(0), st=btn(9); // фронты, не уровни: зажатая кнопка не долбит
  if(a&&!padPrev.a){ const scr=ekran(); if(scr==='menu') runStart(); else if(scr==='over') retryRun(); }
  if(st&&!padPrev.st){ const scr=ekran(); if(scr==='game') pauseGame(); else if(scr==='pause') resumeGame(); }
  padPrev.a=a; padPrev.st=st;
}
/* v1.280.0 «Второй канал»: вибро-геймпада — тот же принцип, что у haptic() для тача/Telegram,
   просто третий, независимый выход. Свежий опрос устройств каждый раз, как и в pollGamepad() —
   ничего не кэшируется между кадрами, штурвал может отстыковаться в любой момент. */
function gamepadRumble(strength, durationMs){
  if(typeof navigator==='undefined'||typeof navigator.getGamepads!=='function') return;
  try{
    const pads=navigator.getGamepads();
    for(let i=0;i<pads.length;i++){
      const gp=pads[i];
      if(gp&&gp.connected&&gp.vibrationActuator){
        gp.vibrationActuator.playEffect('dual-rumble',
          {duration:durationMs, strongMagnitude:strength, weakMagnitude:strength*.6}).catch(()=>{});
        break; // один штурвал активен за раз — хватит первого найденного
      }
    }
  }catch(e){}
}

/* v1.282.13 «Клавиши знают своё место». Две беды сразу.
   Первая: штурвал перехватывал буквы, когда игрок печатал. Позывной, название трассы,
   код друга — в них нельзя было ввести w/a/s/d и пробел (preventDefault съедал), а
   стрелки уводило у ползунков Кузницы вместо перемещения бегунка.
   Вторая, злее: сочетания вроде Ctrl+W или Cmd+S ловились по коду физической клавиши,
   руль вставал в true — а keyup до окна уже не доходил (браузер забирал сочетание себе),
   и клавиша оставалась ЗАЛИПШЕЙ: самолёт уводило до конца забега.
   Оба случая закрываются одной проверкой на входе. */
function keysBusy(e){
  if(e.ctrlKey||e.metaKey||e.altKey) return true;      // сочетание принадлежит системе, не рулю
  const t=e.target;
  if(!t||!t.tagName) return false;
  const tag=t.tagName.toUpperCase();
  return tag==='INPUT'||tag==='TEXTAREA'||tag==='SELECT'||t.isContentEditable===true;
}
window.addEventListener('keydown',e=>{
  if(keysBusy(e)) return;
  const k=e.key, c=e.code; // v1.108.1 «Честная клавиатура»: код физической клавиши, не символ раскладки —
  // раньше 'a'/'A' не срабатывало на AZERTY/QWERTZ (там на месте W/A/S/D другие буквы), только на QWERTY/ЙЦУКЕН
  if(k==='ArrowLeft'||c==='KeyA'){input.keyL=true;e.preventDefault();}
  if(k==='ArrowRight'||c==='KeyD'){input.keyR=true;e.preventDefault();}
  if(k==='ArrowUp'||c==='KeyW'){input.keyU=true;e.preventDefault();}
  if(k==='ArrowDown'||c==='KeyS'){input.keyD=true;e.preventDefault();}
  if(k===' '||k==='Enter'){ const scr=ekran(); if(scr==='menu') runStart(); else if(scr==='over') retryRun(); e.preventDefault(); } // как главная кнопка экрана: выбранная дисциплина, не всегда классика
  if(k==='Escape'||c==='KeyP'){ const scr=ekran(); if(scr==='game') pauseGame(); else if(scr==='pause') resumeGame(); }
});
window.addEventListener('keyup',e=>{
  // v1.282.13: отпускание слушаем ВСЕГДА, без фильтра. Поднять руль обязаны в любом
  // случае — иначе клавиша, зажатая до того, как фокус ушёл в поле ввода, залипнет.
  const k=e.key, c=e.code;
  if(k==='ArrowLeft'||c==='KeyA')input.keyL=false;
  if(k==='ArrowRight'||c==='KeyD')input.keyR=false;
  if(k==='ArrowUp'||c==='KeyW')input.keyU=false;
  if(k==='ArrowDown'||c==='KeyS')input.keyD=false;
});
