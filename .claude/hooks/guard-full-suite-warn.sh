# 26.09.2026: логика вынесена в lib/check-guard-mjs-invocation.mjs — найдено живьём
# в ЭТОЙ ЖЕ сессии, что старый инлайновый `node -e "..."` внутри двойных кавычек
# bash ломал собственный regex ([\/\\] схлопывался bash'ем в [\/\], незакрытый
# класс символов — SyntaxError на каждом вызове). Заодно чинит и старую дыру:
# подстрочное совпадение '*guard.mjs*' срабатывало на ЛЮБОМ файле, чьё имя
# оканчивается на '-guard.mjs' (ask-then-act-guard.mjs и т.п.) — теперь сравнение
# точного basename, не подстроки.
# 30.09.2026: переключатель только у ВЛАДЕЛЬЦА — правкой команды этого хука в settings.json
# ("GUARD_LOCAL_MODE=allow .claude/hooks/guard-full-suite-warn.sh"), тот же приём, что PROTECT_CORE_MODE=off.
# В самой команде Bash я поставить это не могу: переменная окружения команды до хука не доходит.
if [[ "${GUARD_LOCAL_MODE:-}" == "allow" ]]; then exit 0; fi
input=$(cat)
out=$(printf '%s' "$input" | node "$(dirname "$0")/lib/check-guard-mjs-invocation.mjs")
tool=$(printf '%s' "$out" | sed -n '1p')
shouldBlock=$(printf '%s' "$out" | sed -n '2p')
bg=$(printf '%s' "$out" | sed -n '3p')

if [[ "$tool" == "Bash" && "$shouldBlock" == "1" ]]; then
  # 25.09.2026, поймано в этой же сессии сразу после подъёма до "deny": старое условие
  # ловило ЛЮБОЕ упоминание строки "guard.mjs" в команде — блокировало даже безобидный
  # `git diff -- tests/guard.mjs`, не только реальный запуск. Требуем токен "node" тоже
  # в команде — так ловится именно исполнение (`node tests/guard.mjs`), не чтение/diff
  # файла по пути.
  # 25.09.2026 (владелец, резко, после 4-го случая за 17.09/19.09/24.09/25.09×2):
  # "ask" оказался слишком слабым — не мешал вообще НАБРАТЬ и отправить команду,
  # только просил подтверждения в моменте, которое можно (и было) машинально
  # утвердить под потоком задач. Поднято до "deny": набрать и отправить эту
  # команду больше нельзя вообще, без исключений. Единственный легитимный путь —
  # `.github/workflows/guard.yml` на GitHub (сам по расписанию/push, или владелец
  # вручную через workflow_dispatch), не эта машина. Подключено к живому трейлу
  # rules — сама попытка (даже пойманная) значимый паттерн, стоит отслеживания.
  # 30.09.2026: тест хука ставит GUARD_HOOK_TEST=1 — чтобы проверки не писали ложные «попытки» в живой журнал
