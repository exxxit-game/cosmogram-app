#!/usr/bin/env bash
# 19.09.2026 (владелец, напрямую: «шахматное мышление» исчезает при каждом
# сжатии диалога — марафонские сессии сжимаются постоянно, вручную «не забыть
# перечитать файл» не работает). Штатный путь платформы (SessionStart, matcher
# "compact" — подтверждено официальной документацией Claude Code, не выдумано):
# вместо того чтобы полагаться на память модели, ЭТОТ хук технически, сам,
# без участия модели, кладёт живое состояние обратно в контекст СРАЗУ после
# компакции — раньше, чем модель успеет отреагировать на следующее сообщение.
# См. AI-WORKFLOW.md, раздел «Живой приоритет задач переживает сжатие диалога».
STATE_FILE="$(dirname "$0")/../../.knowledge/SESSION-STATE.md"
if [ -f "$STATE_FILE" ]; then
  echo "=== Диалог только что сжался (компакция). Живое состояние сессии — прочитать ПЕРЕД любым действием: ==="
  # 30.09.2026: раньше здесь был cat всего файла — 196 КБ (около 50 тыс. токенов) на каждом старте и после
  # каждого из 65 сжатий, из них 34 записи «САМОЕ СВЕЖЕЕ», большинство давно устарело. Теперь — только первая
  # запись (самая новая); полный файл лежит на диске, читать по нужде.
  awk 'NR==1{print;next} /^## /{exit} {print}' "$STATE_FILE"
  echo "--- (показана только первая запись; полный файл: .knowledge/SESSION-STATE.md, читать по нужде) ---"
else
  echo "=== Компакция произошла, но .knowledge/SESSION-STATE.md не найден — свериться с владельцем, не додумывать открытые задачи. ==="
fi
