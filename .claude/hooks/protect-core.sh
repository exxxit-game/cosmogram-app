#!/usr/bin/env bash
# 25.08.2026: правило проекта «ядро не трогать без явной просьбы» — закреплено
# не текстом в CLAUDE.md (модель может забыть), а тут: технический отказ.
# chmod 444 — подстраховка на случай известного бага, когда deny у Edit
# иногда игнорируется (issue #37210 в anthropics/claude-code).
#
# 26.08.2026: было на jq — jq на этой машине не установлен вовсе (проверено:
# PATH и PowerShell Get-Command молчат), хук молча не срабатывал ВСЮ сессию —
# core.js/render.js правились без единого отказа не потому что «разрешение
# уже было», а потому что защита физически не читала вход. Ноль ошибок наружу,
# выглядело как «работает». Переписано на node — он есть точно, и это тот же
# язык, что у остального проекта (закон «чистый JS»).
#
# 26.08.2026, вечер: «deny» был безусловным — блокировал даже после того, как
# владелец явно разрешал правку словами в чате несколько раз подряд (хук не
# читает разговор, ему неоткуда знать про разрешение). Дошло до того, что
# правки обходили через Bash — а это уже "обойти защиту", чего сам же проект
# запрещает. Настоящее решение — штатное значение permissionDecision:"ask"
# (Claude Code Hooks Guide, PreToolUse): вместо тихого отказа хук теперь
# показывает владельцу обычное окно «Разрешить/Отклонить», то же самое, что
# уже есть для команд в терминале. Разрешение — за владельцем, каждый раз
# заново, никакого файла-ключа и никакого самостоятельного обхода. chmod 444
# снят: он был подстраховкой именно под безусловный deny, а с "ask" может
# помешать уже одобренной владельцем правке — сама очередь разрешений теперь
# у Claude Code, а не у прав файла на диске.
#
# 29.09.2026, ЖИВОЙ ПРОВАЛ (владелец, ревизия): сегодня же core.js/js/ui.js/
# index.html правились несколько раз подряд (разрешение мерж-конфликта) — ни
# ОДНОГО окна разрешения владелец не видел. Проверено пошагово, не на веру:
# хук зарегистрирован в settings.json верно, скрипт технически работает верно
# (прямой тест — правильный JSON с permissionDecision:"ask"), режим сессии —
# "default", не bypassPermissions. Причина осталась НЕ НАЙДЕНА с моей стороны —
# либо платформенный баг (та же природа, что уже задокументированный issue
# про молчаливо игнорируемый deny — 26.08 выше), либо что-то в настройках
# самого приложения/Remote Control, что я кодом проверить не могу. Владелец
# явно выбрал: временно ужесточить обратно на "deny", раз "ask" не работает,
# а не оставлять молчаливую дыру именно в защите ядра. Минус этого решения —
# тот же самый, что уже описан выше в записи 26.08 (deny не различает "ещё не
# разрешено" от "уже явно разрешено словами в чате") — сознательно принят как
# временный, до выяснения причины молчания "ask".
if [[ "${PROTECT_CORE_MODE:-}" == "off" ]]; then
  # Временный обход на явно ограниченное время (владелец в чате разрешил конкретную правку,
  # которую deny блокирует без учёта разговора) — включается правкой команды в settings.json
  # ("PROTECT_CORE_MODE=off .claude/hooks/protect-core.sh", тот же приём, что уже у
  # claim-check-hook/evidence-anchoring-guard и др. с ENFORCE_MODE), не постоянный флаг —
  # вернуть команду в settings.json к исходному виду сразу после разрешённой правки.
  exit 0
fi
input=$(cat)
out=$(printf '%s' "$input" | node -e "
let d='';process.stdin.on('data',c=>d+=c);
process.stdin.on('end',()=>{
  try{ const j=JSON.parse(d);
    process.stdout.write((j.tool_name||'')+'\n'+((j.tool_input&&j.tool_input.file_path)||'')+'\n');
  }catch(e){ process.stdout.write('\n\n'); }
});
")
tool=$(printf '%s' "$out" | sed -n '1p')
file=$(printf '%s' "$out" | sed -n '2p')
# 25.09.2026, найдено живым тестом: файловая система Windows регистронезависима
# (Core.js и core.js — один и тот же файл на диске), а bash `case` по умолчанию
# регистрозависим — «Core.js»/«CORE.JS»/«Game.js» проходили мимо защиты молча.
file_lower="${file,,}"

if [[ "$tool" == "Edit" || "$tool" == "Write" ]]; then
  case "$file_lower" in
    *core.js|*game.js|*render.js|*input.js)
      echo '{"hookSpecificOutput":{"hookEventName":"PreToolUse","permissionDecision":"deny","permissionDecisionReason":"Ядровый файл — временно жёсткий deny (29.09.2026: ask молча не показывал окно владельцу, причина не найдена со стороны кода). Если владелец только что явно разрешил именно эту правку — сказать ему, что нужно на время (PROTECT_CORE_MODE=off перед вызовом, или временно поправить settings.json/сам этот хук), выполнить правку, вернуть защиту."}}'
      exit 0
      ;;
    *ui.js|*index.html)
      # 26.09.2026: тот же приём, что у ядра выше — «визуальное только через макет» держалось
      # только словом в CLAUDE.md, hook его не проверял. Живой вечер: правка ui.js прошла
      # без единой остановки, хотя правило требовало макет. ui.js/index.html — где реально
      # рисуется то, что видит игрок; расширено сюда тем же механизмом. 29.09.2026: тот же
      # живой провал "ask" (см. запись у ядра выше) касается и этого блока — тот же файл,
      # тот же механизм, значит и тот же временный откат на deny, не только у ядра.
      echo '{"hookSpecificOutput":{"hookEventName":"PreToolUse","permissionDecision":"deny","permissionDecisionReason":"Визуальный файл — временно жёсткий deny (29.09.2026: ask молча не показывал окно владельцу). Правило «только через макет» остаётся в силе — если владелец явно попросил правку без макета, ему нужно на время снять защиту (PROTECT_CORE_MODE=off или временная правка хука/settings.json), потом вернуть."}}'
      exit 0
      ;;
  esac
fi
exit 0
