#!/usr/bin/env bash
# 26.09.2026: механизация правила «10+ матов подряд = сигнал остановиться, не сигнал
# давить сильнее» (feedback_desyat_matov_signal_ostanovki.md) — до сих пор существовало
# только как текст, который приходилось вспоминать самому в моменте (prospective memory
# failure — см. feedback_issledovanie_disciplina_barer_davlenie_26_09.md). Владелец прямым
# текстом указал искать другие такие же «записано много раз, ни разу не механизировано»
# случаи и чинить их — это первый.
#
# Не блокирует ничего (владелец имеет право говорить как хочет) — только напоминает
# СЕБЕ, в момент получения сообщения, а не полагается на то что вспомню сам посреди
# выполнения задачи.
input=$(cat)
count=$(printf '%s' "$input" | node -e "
let d='';process.stdin.on('data',c=>d+=c);
process.stdin.on('end',()=>{
  try{
    const j=JSON.parse(d);
    const text=(j.prompt||'').toLowerCase();
    const re=/сук[а-я]*|бляд[ья]*|блять|хуй|хуе[а-я]*|хуя|хуё[а-я]*|еба[а-я]*|ёба[а-я]*|пизд[а-я]*|гандон[а-я]*|мудак[а-я]*|долбо[её]б[а-я]*|уёбищ[а-я]*|уебищ[а-я]*|пидор[а-я]*|пидар[а-я]*|залуп[а-я]*|конч[её]н[а-я]*|тварь|ёбан[а-я]*|нахуй|похуй/g;
    const m=text.match(re)||[];
    process.stdout.write(String(m.length));
  }catch(e){ process.stdout.write('0'); }
});
")
if [[ "$count" =~ ^[0-9]+$ ]] && [ "$count" -ge 10 ]; then
  echo "⚠ В этом сообщении ~$count ругательств подряд (порог 10) — по собственному правилу (feedback_desyat_matov_signal_ostanovki.md): это сигнал ЗАМЕДЛИТЬСЯ и тщательнее проверять перед действием, не ускоряться. Не отвечать словами — остановиться перед следующим действием и явно сверить план с правилами, прежде чем действовать." >&2
fi
exit 0
