#!/usr/bin/env bash
# 25.09.2026 (владелец прямо: «это не иронично, это сбой, исследуй причину»). За эту же
# сессию минимум 5 случаев смешения языков В КОДЕ (не в прозе владельцу): «默认» (китайское
# «по умолчанию») в комментарии signal-trail.mjs, «in code-диапазоне»/«блокируем on это»
# (случайные английские слова внутри русского текста), «developments выше» — все в
# код-комментариях, все ПОСЛЕ того, как в этот же разговор пришло необычно много сырых
# цитат на китайском/японском/корейском от исследовательских агентов (蝶の翅, 構造色,
# 剪纸, タップ и т.п.) — гипотеза: плотность иностранного текста в недавнем контексте
# статистически повышает шанс случайной утечки токена именно в быстрой, менее тщательной
# генерации (комментарий к коду), не в прямом ответе владельцу.
#
# В отличие от аналогичной попытки в memory/scan-suspect-tokens.mjs (ОТКАЧЕНО в этой же
# сессии — память легитимно хранит иностранные исследовательские термины) — здесь другой
# домен: код-комментарии .claude/hooks/*.sh/*.mjs пишутся МНОЙ, всегда по-русски (ABSOLUTE
# правило проекта), CJK/арабский/иврит/деванагари там не может быть легитимным почти
# никогда — низкий риск ложных срабатываний, в отличие от memory/.
#
# PostToolUse после Edit/Write — не блокирует (warn), просто ловит то, что иначе
# осталось бы незамеченным до следующего живого чтения файла глазами.
input=$(cat)
out=$(printf '%s' "$input" | node -e "
let d='';process.stdin.on('data',c=>d+=c);
process.stdin.on('end',()=>{
  try{ const j=JSON.parse(d);
    const file=(j.tool_input&&j.tool_input.file_path)||'';
    process.stdout.write(file+'\n');
  }catch(e){ process.stdout.write('\n'); }
});
")
file=$(printf '%s' "$out" | sed -n '1p')

case "$file" in
  *.sh|*.mjs|*.js)
    if [ -f "$file" ]; then
      hits=$(node -e "
        const fs=require('fs');
        const text=fs.readFileSync(process.argv[1],'utf8');
        // CJK-иероглифы+кана+хангыль+арабский+иврит+деванагари — в код-комментариях
        // этого проекта не легитимны почти никогда (в отличие от memory/-файлов).
        const RANGE=/[一-鿿぀-ヿ가-힣؀-ۿ֐-׿ऀ-ॿ]+/g;
        const found=text.match(RANGE)||[];
        if(found.length) console.log([...new Set(found)].join(', '));
      " "$file" 2>/dev/null)
      if [ -n "$hits" ]; then
        echo "⚠ В $file найдены символы вне латиницы/кириллицы (китайский/японский/корейский/арабский/иврит/деванагари): $hits — похоже на случайную утечку языка в комментарий, не намеренный текст. Проверь и почисти." >&2
      fi
    fi
    ;;
esac
exit 0
