/* ============================================================
   РАЗДЕЛЕНИЕ РЕЛИЗА — что уходит игрокам, а что остаётся экипажу
   ============================================================
   Решение владельца от 14.08.2026 (открытый вопрос 6, вариант А).

   Повод: замер живого сайта показал, что `tests/guard.mjs` отдаётся публично целиком —
   344 КБ с описанием каждого потолка и каждой проверки. Серверных исходников там сегодня
   нет только потому, что их не заливали; в нашем дереве они есть, и первая же полная
   заливка их бы опубликовала. Туда же поехали бы документы, среди которых
   «Найдено и не починено» — список ещё не закрытых дыр.

   Правило: наружу уходит ровно то, что скачивает браузер игрока, плюс то, что игра
   обещает показать человеку (политика, условия, лицензия, иконки, манифесты).
   Всё остальное — работа над игрой, а не игра.

   Этот файл — единственный источник правды о разделении. Его читают и сборщик архивов,
   и страж 137: список, живущий в двух местах, разъезжается на первой же правке.        */

/* Папки, уходящие наружу целиком. */
export const PUBLIC_DIRS = ['js/', 'fonts/', 'icons/', 'app/'];

/* Отдельные файлы в корне. `app/` здесь ради страницы-перенаправления, `dev-chat.html` —
   потому что служебный чат открывается с телефона по ссылке и без раздачи бесполезен;
   секретов в нём нет, вход закрыт паролем DEV_KEY (страж 133). */
export const PUBLIC_FILES = [
  '.nojekyll', 'index.html', 'sw.js', 'dev-chat.html',
  'manifest.json', 'manifest.ru.json', 'manifest.en.json',
  'manifest.es.json', 'manifest.pt.json', 'manifest.fr.json',
  'privacy.html', 'terms.html', 'LICENSE', 'CREDITS.txt', 'README.md',
];

/* Что наружу не уходит никогда — с причиной у каждого пункта. */
export const FORBIDDEN = [
  { re: /^tests\//,            why: 'стенд: карта обороны, все пороги и способы проверки' },
  { re: /^_supabase\//,        why: 'серверные исходники: пороги правдоподобия и логика подрезания' },
  { re: /^docs_pack\//,        why: 'документы экипажа' },
  { re: /^bump_version\.py$/,  why: 'инструмент сборки' },
  { re: /^worker\.js$/,        why: 'код воркера: живёт на Cloudflare, в раздаче не нужен' },
  { re: /^dev-chat\.html$/,    why: '', allow: true }, // исключение, объяснено выше
  { re: /\.md$/,               why: 'документы экипажа, включая список незакрытых дыр' },
];

/* Единственное место, где решается «запрещён ли файл наружу». И сборщик, и страж 137
   зовут именно её: первая редакция считала это в двух местах по-разному, и страж честно
   покраснел на README.md — он разрешён поимённо и запрещён правилом «.md». Правило,
   посчитанное дважды, разъезжается на первой же правке. */
export function zapreshen(f) {
  if (PUBLIC_FILES.includes(f)) return null;      // поимённое разрешение сильнее общего запрета
  return FORBIDDEN.find(r => r.re.test(f) && !r.allow) || null;
}

/* Делит список файлов репозитория на два. Возвращает {igra, ekipazh, spornye}. */
export function splitTree(files) {
  const igra = [], ekipazh = [], spornye = [];
  for (const f of files) {
    if (!f) continue;
    const pub = PUBLIC_FILES.includes(f) || PUBLIC_DIRS.some(d => f.startsWith(d));
    const zapret = zapreshen(f);
    if (pub && zapret) { spornye.push(f + ' → и разрешён, и запрещён: ' + zapret.why); continue; }
    (pub ? igra : ekipazh).push(f);
  }
  return { igra, ekipazh, spornye };
}

/* Всё, что браузер тянет со страницы: теги src, шрифты и иконки из CSS и разметки.
   Нужно страже — чтобы «публичный» архив не оказался неполным и игра не легла. */
export function nuzhnoStranice(html) {
  const out = new Set();
  const add = (p) => { if (p && !/^(https?:)?\/\//.test(p)) out.add(p.replace(/^\.\//, '').split('?')[0]); };
  for (const m of html.matchAll(/\bsrc="([^"]+)"/g)) add(m[1]);
  for (const m of html.matchAll(/\bhref="([^"]+)"/g)) add(m[1]);
  for (const m of html.matchAll(/url\((['"]?)([^)'"]+)\1\)/g)) add(m[2]);
  return [...out].filter(p => /\.(js|woff2?|png|json|html|txt)$/.test(p));
}
